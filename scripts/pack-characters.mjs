// Reproducible, lossless delivery assets. Run with Node; no external packages.
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {GLTFLoader} from '../vendor/GLTFLoader.js';
import {retargetClip} from '../vendor/SkeletonUtils.js';
import {AnimationClip} from '../vendor/three.module.js';
const dir=new URL('../assets/characters/',import.meta.url);
const names=['silver-outfit','scout-outfit','silver-base','scout-base','silver-hair','scout-hair'];
const manifest={models:{},textures:[]};
async function writeHashed(stem,data,extension){
  const hash=createHash('sha256').update(data).digest('hex').slice(0,12),file=`${stem}-${hash}.${extension}`;
  await fs.writeFile(new URL(file,dir),data);return{file,bytes:data.length};
}
for(const name of names){
  const json=JSON.parse(await fs.readFile(new URL(name+'.gltf',dir),'utf8'));
  const bin=await fs.readFile(new URL(json.buffers[0].uri,dir));delete json.buffers[0].uri;
  for(const image of json.images||[])if(!manifest.textures.includes(image.uri))manifest.textures.push(image.uri);
  const raw=Buffer.from(JSON.stringify(json)),j=Buffer.alloc(Math.ceil(raw.length/4)*4,32),b=Buffer.alloc(Math.ceil(bin.length/4)*4);raw.copy(j);bin.copy(b);
  const glb=Buffer.alloc(28+j.length+b.length);glb.writeUInt32LE(0x46546c67,0);glb.writeUInt32LE(2,4);glb.writeUInt32LE(glb.length,8);glb.writeUInt32LE(j.length,12);glb.writeUInt32LE(0x4e4f534a,16);j.copy(glb,20);glb.writeUInt32LE(b.length,20+j.length);glb.writeUInt32LE(0x004e4942,24+j.length);b.copy(glb,28+j.length);
  manifest.models[name]=await writeHashed(name,gzipSync(glb,{level:9}),'glb.gz');
}
// The baker needs bone transforms only; texture pixels do not affect retargeting.
globalThis.self=globalThis;globalThis.ProgressEvent=class{constructor(type,data){Object.assign(this,data);}};
globalThis.createImageBitmap=async()=>({width:512,height:512,close(){}});
const networkFetch=globalThis.fetch;
globalThis.fetch=async input=>{const url=typeof input==='string'?input:input.url;return url.startsWith('file:')?new Response(await fs.readFile(fileURLToPath(url))):networkFetch(input);};
const loader=new GLTFLoader();
const [outfit,library]=await Promise.all([loader.loadAsync(new URL('silver-outfit.gltf',dir).href),loader.loadAsync(new URL('animations.glb',dir).href)]);
function skeleton(root){root.traverse(o=>{if(o.isSkinnedMesh&&!root.skeleton)root.skeleton=o.skeleton;});return root;}
const target=skeleton(outfit.scene),source=skeleton(library.scene),boneNames=Object.fromEntries(target.skeleton.bones.map(b=>[b.name,b.name]));
const clips=[];
for(const name of ['Idle_Loop','Walk_Loop','Jog_Fwd_Loop','Pistol_Idle_Loop','Pistol_Aim_Neutral','Spell_Simple_Idle_Loop','Roll']){
  const original=library.animations.find(c=>c.name===name);if(!original)throw Error(name);
  const baked=retargetClip(target,source,original,{names:boneNames,hip:'pelvis',fps:24,preserveBonePositions:true});baked.name=name;
  // Preserve every source sample; baking removes runtime conversion, not motion detail.
  const json=AnimationClip.toJSON(baked);delete json.uuid;clips.push(json);
}
const motion=Buffer.from(JSON.stringify(clips));manifest.motion=await writeHashed('motion',gzipSync(motion,{level:9}),'json.gz');manifest.motionFallback=await writeHashed('motion',motion,'json');
await fs.writeFile(new URL('../character-assets.js',import.meta.url),'// Generated by scripts/pack-characters.mjs\nexport const CHARACTER_ASSETS='+JSON.stringify(manifest,null,2)+';\n');
const textureBytes=(await Promise.all(manifest.textures.map(async n=>(await fs.stat(new URL(n,dir))).size))).reduce((a,b)=>a+b,0);
console.log(JSON.stringify({models:manifest.models,motion:manifest.motion,textures:textureBytes,total: Object.values(manifest.models).reduce((n,a)=>n+a.bytes,textureBytes)+manifest.motion.bytes},null,2));
